/**
 * Assigns a budget to the 2025-2026 journal entries that have none.
 *
 *   node docs/accounting-mess/assign-budgets.mjs
 *     -> docs/accounting-mess/budgets.sql
 *     -> docs/accounting-mess/budgets-rollback.sql
 *
 * THE RULES, in the order they are tried
 * --------------------------------------
 * The first three name a thing; the last one is the catch-all, so the specific
 * rules have to run first — Elia Nicolo's May reimbursement carries a FESTIVAL
 * cost centre, and it is still communication.
 *
 *   COMMUNICATION  anything from or to Elia Nicolo, and anything mentioning flyers
 *   TECHNIQUE      Impact Vision
 *   ADMINISTRATION the bank's own charges, the refuge and chalet rentals, and the
 *                  INTERNE cost centre — cash-box corrections and meeting pizzas
 *                  are the association running itself, not an event
 *   EVENTS         everything left that carries a cost centre
 *
 * An entry with no cost centre and no match keeps an empty budget: the ordinary
 * year belongs to no budget any more than it belongs to an event.
 */
import { writeFileSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const EDITION = "2025-2026";

const COMMUNICATION = {
  counterparty: /ELIA NICOLO/i,
  label: /\bfl(y|i)ers?\b/i,
};
const TECHNIQUE = /IMPACT VISION/i;
const ADMIN = {
  counterparty: /^BCV$/,
  label: /frais bancaires|location refuge|refuge|location chalet|chalet/i,
  costCentre: "INTERNE",
};

const rows = readFileSync(join(HERE, "journal-2025-2026-current.psv"), "utf8")
  .trim()
  .split("\n")
  .slice(1)
  .filter((line) => line.includes("|"))
  .map((line) => {
    const [seq, date, account, accountType, amount, counterparty, label, costCentre, budget] = line.split("|");
    return { seq: Number(seq), date, account, accountType, amount, counterparty, label, costCentre, budget };
  })
  .filter((r) => Number.isFinite(r.seq));

const assigned = [];
const skipped = [];
/** Entries that already carry a budget: never rewritten, and never rolled back. */
const alreadyBudgeted = rows.filter((r) => r.budget);

for (const row of rows) {
  if (row.budget) continue;
  const costCentre = row.costCentre;

  let budget = null;
  let why = "";

  if (COMMUNICATION.counterparty.test(row.counterparty) || COMMUNICATION.label.test(row.label)) {
    budget = "COMMUNICATION";
    why = COMMUNICATION.counterparty.test(row.counterparty) ? "Elia Nicolo" : "mentionne des flyers";
  } else if (TECHNIQUE.test(row.counterparty)) {
    budget = "TECHNIQUE";
    why = "Impact Vision";
  } else if (
    ADMIN.counterparty.test(row.counterparty) ||
    ADMIN.label.test(row.label) ||
    costCentre === ADMIN.costCentre
  ) {
    budget = "ADMINISTRATION";
    why = ADMIN.counterparty.test(row.counterparty)
      ? "frais bancaires"
      : costCentre === ADMIN.costCentre
        ? "centre de charge INTERNE"
        : "location refuge / chalet";
  } else if (costCentre) {
    budget = "EVENTS";
    why = `centre de charge ${costCentre}`;
  }

  if (budget) assigned.push({ ...row, budget, why, costCentre });
  else skipped.push(row);
}

const quote = (v) => `'${String(v).replace(/'/g, "''")}'`;

const sql = `-- Assigns a budget to ${assigned.length} entries of the ${EDITION} journal.
-- Generated by docs/accounting-mess/assign-budgets.mjs — do not hand-edit.
-- Only ever fills an EMPTY budget, so it cannot overwrite a decision already
-- made in the app.
\\set ON_ERROR_STOP on

${assigned
  .map(
    (r) => `UPDATE "JournalEntry" j SET "budgetId" = b.id, "updatedAt" = now()
FROM "Budget" b, "Edition" ed
WHERE ed.name = ${quote(EDITION)} AND j."editionId" = ed.id
  AND b."editionId" = ed.id AND b.name = ${quote(r.budget)}
  AND j."sequenceNumber" = ${r.seq} AND j."budgetId" IS NULL;`,
  )
  .join("\n\n")}

SELECT b.name, count(j.id) AS ecritures,
       to_char(sum(CASE WHEN j."accountType" = 'PRODUITS' THEN j.amount ELSE -j.amount END), 'FM999G999D00') AS net
FROM "Budget" b
JOIN "JournalEntry" j ON j."budgetId" = b.id
WHERE b."editionId" = (SELECT id FROM "Edition" WHERE name = ${quote(EDITION)})
GROUP BY b.name ORDER BY b.name;
`;

const rollback = `-- Clears the budget from the ${assigned.length} entries budgets.sql set.
-- Generated by docs/accounting-mess/assign-budgets.mjs — do not hand-edit.
\\set ON_ERROR_STOP on

UPDATE "JournalEntry" SET "budgetId" = NULL, "updatedAt" = now()
WHERE "editionId" = (SELECT id FROM "Edition" WHERE name = ${quote(EDITION)})
  AND "sequenceNumber" IN (${assigned.map((r) => r.seq).sort((a, b) => a - b).join(", ")});
-- The ${alreadyBudgeted.length} entries that already carried a budget before this pass
-- (${alreadyBudgeted.map((r) => r.seq).sort((a, b) => a - b).join(", ")})
-- are deliberately absent from that list.
`;

writeFileSync(join(HERE, "budgets.sql"), sql, "utf8");
writeFileSync(join(HERE, "budgets-rollback.sql"), rollback, "utf8");

const byBudget = {};
for (const r of assigned) (byBudget[r.budget] ||= []).push(r);
for (const name of Object.keys(byBudget).sort()) {
  const list = byBudget[name];
  const reasons = [...new Set(list.map((r) => r.why.replace(/centre de charge .*/, "centre de charge")))];
  console.log(`${name.padEnd(15)} ${String(list.length).padStart(3)}   ${reasons.join(", ")}`);
}
console.log(`${"(sans budget)".padEnd(15)} ${String(skipped.length).padStart(3)}`);
console.log(`${"(déjà budgété)".padEnd(15)} ${String(alreadyBudgeted.length).padStart(3)}   intouché`);
