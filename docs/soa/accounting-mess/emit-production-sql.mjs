/**
 * Turns final-result.csv into the SQL that books it on the production database.
 *
 *   node docs/accounting-mess/emit-production-sql.mjs
 *     -> docs/accounting-mess/apply.sql    (one transaction, run it with psql)
 *     -> docs/accounting-mess/rollback.sql (undoes exactly what apply.sql wrote)
 *
 * Nothing here hardcodes a cuid except the ids of the rows it creates, which are
 * derived from the sequence number so a re-run produces the same ids and the
 * insert stays idempotent under ON CONFLICT. Everything else is looked up by
 * name — edition, money account, cost center — so the script cannot silently
 * write into the wrong edition if an id ever changes.
 */
import { createHash } from "node:crypto";
import { writeFileSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));

const SOURCE_EDITION = "2025-2026";
const TARGET_EDITION = "2026-2027";
const CASH_ACCOUNT = "Coffre";

/** Cost centers the reconstruction needs that the editions do not have yet. */
const NEW_COST_CENTERS = [
  { code: "SVC", name: "SVC" },
  { code: "SEGRILL2", name: "SEGRILL2" },
  { code: "SEGRILL3", name: "SEGRILL3" },
];

/**
 * A stable 25-character id in the shape Prisma's cuid() produces. Derived from
 * a namespace and a key so re-running emits identical ids — that is what makes
 * apply.sql safe to run twice.
 */
const idFor = (namespace, key) =>
  `c${createHash("sha1").update(`${namespace}:${key}`).digest("hex").slice(0, 24)}`;

const quote = (value) => `'${String(value).replace(/'/g, "''")}'`;

/* ------------------------------------------------------------- read the CSV */

const parseCsvLine = (line) => {
  const cells = [];
  let cell = "";
  let quoted = false;
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];
    if (ch === '"') {
      if (quoted && line[i + 1] === '"') {
        cell += '"';
        i += 1;
      } else {
        quoted = !quoted;
      }
      continue;
    }
    if (ch === "," && !quoted) {
      cells.push(cell);
      cell = "";
      continue;
    }
    cell += ch;
  }
  cells.push(cell);
  return cells;
};

const csv = readFileSync(join(HERE, "final-result.csv"), "utf8").trim().split("\n");
const header = parseCsvLine(csv[0]);
const entries = csv.slice(1).map((line) => {
  const cells = parseCsvLine(line);
  return Object.fromEntries(header.map((key, i) => [key, cells[i]]));
});

if (entries.length === 0) throw new Error("final-result.csv holds no rows");
for (const e of entries) {
  if (e.moneyAccount !== CASH_ACCOUNT) throw new Error(`Unexpected account: ${e.moneyAccount}`);
  if (!["PRODUITS", "CHARGES"].includes(e.accountType)) throw new Error(`Bad type: ${e.accountType}`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(e.date)) throw new Error(`Bad date: ${e.date}`);
  if (!/^\d+\.\d{2}$/.test(e.amount)) throw new Error(`Bad amount: ${e.amount}`);
}

const entryIds = entries.map((e) => idFor("blv-coffre-2025-2026", e.sequenceNumber));

/* ------------------------------------------------------------------ apply.sql */

const costCenterInserts = NEW_COST_CENTERS.flatMap(({ code, name }) =>
  [SOURCE_EDITION, TARGET_EDITION].map(
    (edition) => `INSERT INTO "CostCenter" (id, "editionId", code, name, "createdAt", "updatedAt")
SELECT ${quote(idFor("blv-cc", `${edition}:${code}`))}, e.id, ${quote(code)}, ${quote(name)}, now(), now()
FROM "Edition" e WHERE e.name = ${quote(edition)}
ON CONFLICT ("editionId", code) DO NOTHING;`,
  ),
);

const entryInserts = entries.map((e, i) => {
  const costCenter = e.costCenter
    ? `(SELECT cc.id FROM "CostCenter" cc WHERE cc."editionId" = ma."editionId" AND cc.code = ${quote(e.costCenter)})`
    : "NULL";
  return `INSERT INTO "JournalEntry" (
  id, "editionId", "moneyAccountId", "accountType", "sequenceNumber", date, amount,
  counterparty, label, "costCenterId", "isOpeningEntry", "createdAt", "updatedAt")
SELECT ${quote(entryIds[i])}, ma."editionId", ma.id, ${quote(e.accountType)}::"AccountType", ${e.sequenceNumber},
       ${quote(e.date)}::timestamp, ${e.amount}, ${quote(e.counterparty)}, ${quote(e.label)},
       ${costCenter}, false, now(), now()
FROM "MoneyAccount" ma
JOIN "Edition" ed ON ed.id = ma."editionId"
WHERE ed.name = ${quote(SOURCE_EDITION)} AND ma.name = ${quote(CASH_ACCOUNT)}
ON CONFLICT (id) DO NOTHING;`;
});

const apply = `-- Books the reconstituted 2025-2026 cash box and re-carries its balance.
--
-- Generated by docs/accounting-mess/emit-production-sql.mjs — do not hand-edit.
-- Run inside a single transaction:
--   psql -U blv -d baleinev_comptes -v ON_ERROR_STOP=1 --single-transaction -f apply.sql
--
-- Re-running is safe: every insert is ON CONFLICT DO NOTHING on a deterministic
-- id, and the carry-over UPDATE recomputes from the source edition each time.

\\set ON_ERROR_STOP on

-- 1. The cost centers the reconstruction needs, in both editions so the new
--    year inherits the same chart the carry-over would have copied.
${costCenterInserts.join("\n\n")}

-- 2. The ${entries.length} reconstructed cash movements, sequences
--    ${entries[0].sequenceNumber}-${entries.at(-1).sequenceNumber}. Nothing existing is touched.
${entryInserts.join("\n\n")}

-- 3. Re-carry the cash box into ${TARGET_EDITION}. The amount is recomputed from
--    the source edition rather than typed, so it cannot disagree with step 2.
--    The bank account's carry-over is already correct and is left alone.
WITH closing AS (
  SELECT ma."openingBalance" + COALESCE(SUM(
           CASE WHEN j."accountType" = 'PRODUITS' THEN j.amount ELSE -j.amount END
         ), 0) AS balance
  FROM "MoneyAccount" ma
  JOIN "Edition" ed ON ed.id = ma."editionId"
  LEFT JOIN "JournalEntry" j ON j."moneyAccountId" = ma.id
  WHERE ed.name = ${quote(SOURCE_EDITION)} AND ma.name = ${quote(CASH_ACCOUNT)}
  GROUP BY ma.id, ma."openingBalance"
)
UPDATE "JournalEntry" j
SET "accountType" = CASE WHEN closing.balance >= 0 THEN 'PRODUITS' ELSE 'CHARGES' END::"AccountType",
    amount        = abs(closing.balance),
    "updatedAt"   = now()
FROM closing, "MoneyAccount" ma, "Edition" ed
WHERE j."moneyAccountId" = ma.id
  AND ma."editionId" = ed.id
  AND ed.name = ${quote(TARGET_EDITION)}
  AND ma.name = ${quote(CASH_ACCOUNT)}
  AND j."isOpeningEntry" = true;

-- 4. What the two editions look like afterwards.
SELECT ed.name AS edition, ma.name AS compte,
       ma."openingBalance" + COALESCE(SUM(
         CASE WHEN j."accountType" = 'PRODUITS' THEN j.amount ELSE -j.amount END
       ), 0) AS solde,
       count(j.id) AS ecritures
FROM "MoneyAccount" ma
JOIN "Edition" ed ON ed.id = ma."editionId"
LEFT JOIN "JournalEntry" j ON j."moneyAccountId" = ma.id
WHERE ed.name IN (${quote(SOURCE_EDITION)}, ${quote(TARGET_EDITION)})
GROUP BY ed.name, ma.name, ma.id, ma."openingBalance"
ORDER BY ed.name, ma.name;
`;

/* --------------------------------------------------------------- rollback.sql */

const rollback = `-- Undoes apply.sql exactly: deletes the ${entries.length} rows it inserted, drops the
-- three cost centers it created, and puts the ${TARGET_EDITION} cash carry-over back to
-- the value it held before (CHARGES 6554.03, written by the 24.08.2026 carry-over).
--
-- Generated by docs/accounting-mess/emit-production-sql.mjs — do not hand-edit.

\\set ON_ERROR_STOP on

DELETE FROM "JournalEntry" WHERE id IN (
${entryIds.map((id) => `  ${quote(id)}`).join(",\n")}
);

DELETE FROM "CostCenter" WHERE id IN (
${NEW_COST_CENTERS.flatMap(({ code }) =>
  [SOURCE_EDITION, TARGET_EDITION].map((edition) => `  ${quote(idFor("blv-cc", `${edition}:${code}`))}`),
).join(",\n")}
);

UPDATE "JournalEntry" j
SET "accountType" = 'CHARGES'::"AccountType", amount = 6554.03, "updatedAt" = now()
FROM "MoneyAccount" ma, "Edition" ed
WHERE j."moneyAccountId" = ma.id
  AND ma."editionId" = ed.id
  AND ed.name = ${quote(TARGET_EDITION)}
  AND ma.name = ${quote(CASH_ACCOUNT)}
  AND j."isOpeningEntry" = true;
`;

writeFileSync(join(HERE, "apply.sql"), apply, "utf8");
writeFileSync(join(HERE, "rollback.sql"), rollback, "utf8");

console.log(`apply.sql    : ${NEW_COST_CENTERS.length * 2} cost centers, ${entries.length} entries, 1 carry-over update`);
console.log(`rollback.sql : deletes the same ${entries.length} ids and ${NEW_COST_CENTERS.length * 2} cost centers`);
console.log(`entry ids    : ${entryIds[0]} … ${entryIds.at(-1)}`);
